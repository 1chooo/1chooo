package main

import (
	"fmt"
	"go/format"
	"os"
	"path"
	"path/filepath"
	"strings"
)

const typesPerFile = 80

func emit(m *schemaModel, outDir, pkg string) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}

	var goKeywords = map[string]struct{}{
		"break": {}, "case": {}, "chan": {}, "const": {}, "continue": {}, "default": {},
		"defer": {}, "else": {}, "fallthrough": {}, "for": {}, "func": {}, "go": {},
		"goto": {}, "if": {}, "import": {}, "interface": {}, "map": {}, "package": {},
		"range": {}, "return": {}, "select": {}, "struct": {}, "switch": {}, "type": {},
		"var": {},
	}

	header := `// Code generated by internal/schemaorg-gen from schema.org N-Triples; DO NOT EDIT.
// Regenerate: ./scripts/gen-schemaorg.sh (or: go run ./internal/schemaorg-gen -ontology FILE.nt -o ./schemaorggen)
// Ontology: https://schema.org/version/latest/schemaorg-all-https.nt

`

	// doc.go
	doc := header + "package " + pkg + "\n\n" +
		"// Package " + pkg + " contains generated Go structs mirroring schema.org types for JSON-LD,\n" +
		"// similar in spirit to https://github.com/google/schema-dts (generated from the same ontology family).\n" +
		"// Set JSONLDType to the matching Type* constant when building a value.\n" +
		"// Object-typed fields use any where the vocabulary allows multiple range types.\n" +
		"// For root documents, add \"@context\" via an outer struct embedding your type; see [SchemaContextURL].\n"
	if err := os.WriteFile(filepath.Join(outDir, "doc.go"), []byte(doc), 0o644); err != nil {
		return err
	}

	// Constants file
	var constB strings.Builder
	constB.WriteString(header)
	constB.WriteString("package " + pkg + "\n\nconst (\n")
	for _, cURI := range m.Classes {
		goName, err := goTypeName(cURI)
		if err != nil {
			continue
		}
		jsonType := path.Base(cURI)
		constB.WriteString(fmt.Sprintf("\tType%s = %q\n", goName, jsonType))
	}
	constB.WriteString(")\n")
	if err := writeGo(filepath.Join(outDir, "z_const.go"), constB.String()); err != nil {
		return err
	}

	// Split type structs
	fileIdx := 0
	var cur strings.Builder
	count := 0

	flush := func() error {
		if cur.Len() == 0 {
			return nil
		}
		name := fmt.Sprintf("z_types_%03d.go", fileIdx)
		fileIdx++
		s := header + "package " + pkg + "\n\n" + cur.String()
		if err := writeGo(filepath.Join(outDir, name), s); err != nil {
			return err
		}
		cur.Reset()
		count = 0
		return nil
	}

	for _, cURI := range m.Classes {
		goName, err := goTypeName(cURI)
		if err != nil {
			continue
		}
		if count == 0 {
			cur.Reset()
		}
		props := propertiesForClass(m, cURI)
		var b strings.Builder
		b.WriteString(fmt.Sprintf("// %s is https://schema.org/%s\n", goName, goName))
		b.WriteString(fmt.Sprintf("type %s struct {\n", goName))
		b.WriteString("\tJSONLDType string `json:\"@type\"`\n")
		for _, p := range props {
			gf := p.GoField
			if _, kw := goKeywords[strings.ToLower(gf)]; kw {
				gf = "_" + gf
			}
			if gf == "JSONLDType" {
				gf = "XJSONLDTypeConflict"
			}
			b.WriteString(fmt.Sprintf("\t%s %s `json:\"%s,omitempty\"`\n", gf, p.GoType, p.JSONName))
		}
		b.WriteString("}\n\n")
		cur.WriteString(b.String())
		count++
		if count >= typesPerFile {
			if err := flush(); err != nil {
				return err
			}
		}
	}
	if err := flush(); err != nil {
		return err
	}

	return nil
}

func writeGo(path, src string) error {
	out, err := format.Source([]byte(src))
	if err != nil {
		return fmt.Errorf("format %s: %w\n---\n%s", path, err, src)
	}
	return os.WriteFile(path, out, 0o644)
}
